class ComparatorParityTests(unittest.TestCase):
    def test_sort_rows_matches_the_frontend_order_for_every_column(self) -> None:
        for name, values in JS_COLUMNS.items():
            rows = [{"i": i, "v": v} for i, v in enumerate(values)]
            for direction in (ASC, DESC):
                with self.subTest(column=name, direction=direction):
                    got = [r["i"] for r in ao.sort_rows(rows, _order(("v", direction)))]
                    self.assertEqual(got, JS_ORDERS[name][direction])

    def test_numbers_compare_numerically_including_numeric_strings(self) -> None:
        self.assertLess(ao.compare_cell_values(2, 10), 0)
        self.assertLess(ao.compare_cell_values("9", "10"), 0, "numeric, not '9' > '1'")
        self.assertEqual(ao.compare_cell_values("7", 7), 0)
        self.assertLess(ao.compare_cell_values(" 8 ", "1e2"), 0, "JS Number() trims and reads 1e2")
        self.assertEqual(ao.compare_cell_values("0x10", 16), 0, "JS Number('0x10') is 16")
        self.assertEqual(ao.compare_cell_values(True, 1), 0, "Number(true) is 1")
        self.assertEqual(ao.compare_cell_values([5], "5"), 0, "Number([5]) is 5")

    def test_empty_values(self) -> None:
        # null/missing sorts after everything ascending ...
        self.assertGreater(ao.compare_cell_values(None, "a"), 0)
        self.assertGreater(ao.compare_cell_values(None, 0), 0)
        self.assertEqual(ao.compare_cell_values(None, None), 0)
        # ... and '' is NOT numeric (the frontend's `a !== ''` guard): it
        # string-compares, so it sorts before '5', not as 0 against 5.
        self.assertLess(ao.compare_cell_values("", "5"), 0)
        self.assertLess(ao.compare_cell_values("", -1), 0, "as 0 it would sort after -1")
        # An empty array is Number([]) = 0 and isn't '' → numeric.
        self.assertEqual(ao.compare_cell_values([], 0), 0)

    def test_descending_puts_nulls_first(self) -> None:
        rows = [{"v": None}, {"v": 1}, {"v": 2}]
        self.assertEqual([r["v"] for r in ao.sort_rows(rows, _order(("v", DESC)))], [None, 2, 1])
        self.assertEqual([r["v"] for r in ao.sort_rows(rows, _order(("v", ASC)))], [1, 2, None])

    def test_arrays_compare_by_their_formatted_text(self) -> None:
        self.assertEqual(ao.format_cell(["b", "a"]), "b, a")
        self.assertEqual(ao.format_cell([{"name": "Amy"}]), '{"name":"Amy"}')
        self.assertLess(ao.compare_cell_values(["a", "b"], ["a", "c"]), 0)
        self.assertLess(ao.compare_cell_values(["a"], ["a", "b"]), 0)

    def test_strings_are_natural_and_case_insensitive(self) -> None:
        self.assertLess(ao.compare_cell_values("item 2", "item 10"), 0)
        self.assertLess(ao.compare_cell_values("apple", "Banana"), 0)
        self.assertLess(ao.compare_cell_values("apple", "Apple"), 0, "lowercase first on a case tie")
        self.assertLess(ao.compare_cell_values("eclair", "éclair"), 0, "accent after base")
        self.assertLess(ao.compare_cell_values("éclair", "fig"), 0, "accents are secondary")

    def test_js_number_and_string_ports(self) -> None:
        cases = {
            "": 0.0, " ": 0.0, "  12 ": 12.0, "0x1A": 26.0, "0b101": 5.0, "0o17": 15.0,
            "1e3": 1000.0, ".5": 0.5, "5.": 5.0, "+5": 5.0, "  3": 3.0,
        }
        for text, expected in cases.items():
            self.assertEqual(ao.js_number(text), expected, repr(text))
        for text in ("-0x1A", "1_000", "12abc", "infinity", "١٢", "0x"):
            self.assertTrue(ao.js_number(text) != ao.js_number(text), f"NaN expected: {text!r}")
        self.assertTrue(ao.js_number({}) != ao.js_number({}))
        self.assertTrue(ao.js_number([1, 2]) != ao.js_number([1, 2]))
        for value, text in ((3.0, "3"), (1e21, "1e+21"), (1e-7, "1e-7"), (1.5e-6, "0.0000015"),
                            (1e16, "10000000000000000"), (-42.0, "-42"), (0.1, "0.1")):
            self.assertEqual(ao._js_number_to_string(value), text)

    def test_sort_rows_equals_the_comparator_on_consistent_columns(self) -> None:
        """The per-level key fast paths agree with `compare_cell_values`
        itself (numeric-only and string-only columns, with nulls)."""
        rng = random.Random(7)
        words = ["Todo", "todo", "In progress", "Done", "done", "n/a", "été", "ete", "item 3", "item 20"]
        columns = {
            "num": [rng.choice([None, rng.randint(-50, 50), str(rng.randint(0, 9)), rng.random()]) for _ in range(300)],
            "str": [rng.choice([None] + words) for _ in range(300)],
        }
        for name, values in columns.items():
            rows = [{"i": i, "v": v} for i, v in enumerate(values)]
            for direction in (ASC, DESC):
                sign = 1 if direction == ASC else -1
                expected = sorted(
                    rows, key=cmp_to_key(lambda a, b: sign * ao.compare_cell_values(a["v"], b["v"]))
                )
                with self.subTest(column=name, direction=direction):
                    self.assertEqual(ao.sort_rows(rows, _order(("v", direction))), expected)

    def test_ascii_fast_path_equals_the_general_collation(self) -> None:
        rng = random.Random(3)
        alphabet = [chr(i) for i in range(128)]
        samples = alphabet + [
            "".join(rng.choice(alphabet) for _ in range(rng.randint(0, 12))) for _ in range(3000)
        ]
        for text in samples:
            self.assertEqual(ao._ascii_collation_key(text), ao._general_collation_key(text), repr(text))

    def test_group_then_sort_and_stable_ties(self) -> None:
        rows = [
            {"id": "a", "Status": "Todo", "Amount": 5},
            {"id": "b", "Status": "Done", "Amount": 1},
            {"id": "c", "Status": "Todo", "Amount": 9},
            {"id": "d", "Status": "Done", "Amount": 1},
            {"id": "e", "Status": None, "Amount": 3},
        ]
        got = ao.sort_rows(rows, _order(("Status", ASC), ("Amount", DESC)))
        # Done (1,1: b before d, original order) → Todo (9, 5) → null group last.
        self.assertEqual([r["id"] for r in got], ["b", "d", "c", "a", "e"])

    def test_sort_rows_never_mutates_its_input(self) -> None:
        rows = [{"v": 3}, {"v": 1}, {"v": 2}]
        snapshot = list(rows)
        out = ao.sort_rows(rows, _order(("v", ASC)))
        self.assertEqual(rows, snapshot)
        self.assertIsNot(out, rows)
        self.assertEqual(ao.sort_rows(rows, []), rows)


