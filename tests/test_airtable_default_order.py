class DefaultOrderParsingTests(unittest.TestCase):
    def test_parse_accepts_only_well_formed_values(self) -> None:
        self.assertEqual(ao.parse_default_order({"field": "A", "direction": "desc"}), {"field": "A", "direction": "desc"})
        for bad in (None, "A", [], {}, {"field": "A"}, {"field": "", "direction": "asc"},
                    {"field": "  ", "direction": "asc"}, {"field": 3, "direction": "asc"},
                    {"field": "A", "direction": "up"}, {"field": "A", "direction": None}):
            self.assertIsNone(ao.parse_default_order(bad), repr(bad))

    def test_group_comes_first_and_a_duplicate_field_is_dropped(self) -> None:
        self.assertEqual(
            ao.widget_default_order(
                default_group={"field": "G", "direction": "desc"},
                default_sort={"field": "S", "direction": "asc"},
            ),
            _order(("G", DESC), ("S", ASC)),
        )
        self.assertEqual(
            ao.widget_default_order(
                default_group={"field": "G", "direction": "asc"},
                default_sort={"field": "G", "direction": "desc"},
            ),
            _order(("G", ASC)),
        )
        self.assertEqual(
            ao.widget_default_order(default_group=None, default_sort={"field": "S", "direction": "asc"}),
            _order(("S", ASC)),
        )
        self.assertEqual(ao.widget_default_order(default_group="junk", default_sort=None), [])

    def test_restrict_drops_hidden_columns(self) -> None:
        order = _order(("Hidden", ASC), ("Shown", DESC))
        self.assertEqual(ao.restrict_order_to_fields(order, ["Shown"]), _order(("Shown", DESC)))
        self.assertEqual(ao.restrict_order_to_fields(None, ["Shown"]), [])

    def test_default_group_validity_for_the_gate(self) -> None:
        group = {"field": "Status", "direction": "asc"}
        self.assertTrue(ao.default_group_is_valid({"defaultGroup": group}))
        self.assertTrue(ao.default_group_is_valid({"defaultGroup": group, "selectedColumns": []}))
        self.assertTrue(ao.default_group_is_valid({"defaultGroup": group, "selectedColumns": ["Status"]}))
        self.assertFalse(ao.default_group_is_valid({"defaultGroup": group, "selectedColumns": ["Name"]}))
        self.assertFalse(ao.default_group_is_valid({"defaultGroup": {"field": "Status"}}))
        self.assertFalse(ao.default_group_is_valid({"defaultSort": group}))
        self.assertFalse(ao.default_group_is_valid(None))

    def test_airtable_sort_option(self) -> None:
        self.assertEqual(ao.airtable_sort_option(_order(("G", DESC), ("S", ASC))), ["-G", "S"])
        self.assertEqual(ao.airtable_sort_option(None), [])
        # A '-'-named field: descending survives pyairtable's prefix parse,
        # ascending can't be expressed and is skipped.
        self.assertEqual(ao.airtable_sort_option(_order(("-x", DESC))), ["--x"])
        self.assertEqual(ao.airtable_sort_option(_order(("-x", ASC))), [])


